ECHO_DATA = re.compile(r'^echo/data/')
ECHO_DATA_KEEP = re.compile(r'^echo/data/cache/(seq_)?val_[^/]+$')


# Board-regression data: a separate zip (see the docstring).
REGRESSION_DATA = ['echo/data/*', 'echo/results/quant/*/click_inputs/*', 'echo/results/quant/*/seq_inputs/*']


def is_regression_data(rel):
    return any(fnmatch.fnmatch(rel, p) for p in REGRESSION_DATA)


def included(rel):
    if any(fnmatch.fnmatch(rel, p) for p in KEEP):
        return True
    if any(fnmatch.fnmatch(rel, p) for p in EXCLUDE):
        return False
    if HLS_BUILD.match(rel):
        return bool(HLS_BUILD_KEEP.match(rel))
    if RX_HLS.match(rel):
        return bool(RX_HLS_KEEP.match(rel))
    if ECHO_DATA.match(rel):
        return bool(ECHO_DATA_KEEP.match(rel))
    m = NETWORK_IMAGES.match(rel)
    if m and m.group(1) != KEEP_NETWORK_IMAGE:
        return False
    m = LWNET_RESULTS.match(rel)
    if m and m.group(1) != 'quant_sensitivity':
        return '/' not in m.group(2) and rel.endswith(('.md', '.json', '.png', '.csv'))
    return True


def collect():
    files = []
    for dirpath, dirnames, filenames in os.walk(ROOT):
        rel_dir = os.path.relpath(dirpath, ROOT).replace(os.sep, '/')
        rel_dir = '' if rel_dir == '.' else rel_dir + '/'
        # Prune whole excluded trees early (the image, venv and build folders are large).
        dirnames[:] = [d for d in dirnames
                       if any(fnmatch.fnmatch(rel_dir + d + '/x', p) for p in KEEP)
                       or not any(fnmatch.fnmatch(rel_dir + d + '/x', p) for p in EXCLUDE)]
        for name in filenames:
            rel = rel_dir + name
            if included(rel):
                files.append(rel)
    return sorted(files)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--list', action='store_true')
    parser.add_argument('--output', default=os.path.join(ROOT, 'share', 'PLD_share_%s.zip' % time.strftime('%Y%m%d')))
    args = parser.parse_args()
    files = collect()
    raw = sum(os.path.getsize(os.path.join(ROOT, f)) for f in files)
    if args.list:
        for f in files:
            print(f)
        print('%d files, %.1f MB before compression' % (len(files), raw / 1e6))
        return 0
    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    top = 'PLD'
    data_out = args.output[:-4] + '_regression_data.zip'
    for out, part in ((args.output, [f for f in files if not is_regression_data(f)]),
                      (data_out, [f for f in files if is_regression_data(f)])):
        with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED, compresslevel=6) as z:
            for f in part:
                z.write(os.path.join(ROOT, f), top + '/' + f)
        size = sum(os.path.getsize(os.path.join(ROOT, f)) for f in part)
        print('%s: %d files, %.1f MB -> %.1f MB' % (out, len(part), size / 1e6, os.path.getsize(out) / 1e6))
    return 0


if __name__ == '__main__':
    sys.exit(main())
