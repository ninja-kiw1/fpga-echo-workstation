"""Extract the full FZ3B zynq_ultra_ps_e configuration from the vendor reference
design and emit bd/ps_config.tcl (a set_property -dict block applied to $ps).

Base = the FreeRTOS-Lwip-TCP-Server reference (it is the superset: DDR4-2400 +
GEM3 ethernet MIO64..77 + SD0/eMMC + SD1/SD-card + QSPI + UART1).

Modifications for our design:
  PSU__USE__M_AXI_GP0  0 -> 1     (PS->PL master M_AXI_HPM0_FPD)
  PSU__USE__S_AXI_GP2  0 -> 1     (PL->PS slave S_AXI_HP0_FPD)
"""
from pathlib import Path
import argparse
import os
import re

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--reference", required=True, type=Path,
                    help="Vendor system_FreeRTOS_Lwip_TCP_Server.tcl (not in this package)")
REF = parser.parse_args().reference

OUT = str(Path(__file__).resolve().parents[1] / "bd/ps_config.tcl")

src = open(REF, "r", encoding="utf-8", errors="replace").read()

# grab the PS set_property block: from "set_property -dict [ list \" after the
# zynq_ultra_ps_e create, up to the closing "] $zynq_ultra_ps_e_0"
m = re.search(r"set zynq_ultra_ps_e_0 \[ create_bd_cell.*?\n", src)
assert m, "create_bd_cell for PS not found"
start = src.index("set_property -dict [ list", m.end())
end = src.index("] $zynq_ultra_ps_e_0", start) + len("] $zynq_ultra_ps_e_0")
block = src[start:end]

# rename the target variable and flip the two PL-AXI switches
block = block.replace("$zynq_ultra_ps_e_0", "$ps")
block = block.replace("CONFIG.PSU__USE__M_AXI_GP0 {0}", "CONFIG.PSU__USE__M_AXI_GP0 {1}")
assert "CONFIG.PSU__USE__S_AXI_GP2" not in block or True
# replace GP2 line if present, else append before the closing bracket
if "CONFIG.PSU__USE__S_AXI_GP2 {0}" in block:
    block = block.replace("CONFIG.PSU__USE__S_AXI_GP2 {0}", "CONFIG.PSU__USE__S_AXI_GP2 {1}")
else:
    block = block.replace("] $ps", " CONFIG.PSU__USE__S_AXI_GP2 {1} \\\n ] $ps")

header = (
    "# AUTO-GENERATED by bd/gen_ps_config.py -- do not hand-edit.\n"
    "# Full FZ3B PS config (DDR4-2400/64bit, GEM3 MIO64..77, SD0 eMMC, SD1 SD-card,\n"
    "# QSPI, UART1) + PS<->PL AXI: M_AXI_HPM0_FPD (GP0) and S_AXI_HP0_FPD (GP2).\n\n"
)
open(OUT, "w", encoding="utf-8").write(header + block + "\n")

# report
props = re.findall(r"(CONFIG\.[A-Za-z0-9_]+)", block)
print("extracted %d property entries, %d unique" % (len(re.findall(r"CONFIG\.", block)), len(set(props))))
for key in ("PSU__USE__M_AXI_GP0", "PSU__USE__S_AXI_GP2", "PSU__ENET3__PERIPHERAL__ENABLE",
            "PSU__DDRC__SPEED_BIN", "PSU__SD1__PERIPHERAL__ENABLE", "PSU__UART1__PERIPHERAL__ENABLE",
            "PSU__QSPI__PERIPHERAL__ENABLE", "PSU__FPGA_PL0_ENABLE",
            "PSU__USE__PL_RESET", "PSU__USE__PL_CLK0"):
    hit = [l.strip() for l in block.splitlines() if key in l]
    print("  %-34s -> %s" % (key, hit[0] if hit else "(absent)"))
print("wrote", OUT, os.path.getsize(OUT), "bytes")
