# -*- coding: utf-8 -*-
"""P5-1: 由 vectors 目录生成板端 C 需要的网络描述。

产出(默认写到 tcp_image_rx/src/):
  unet_net.h       -- 节点表结构 + 配置宏 + extern 声明
  unet_net_data.c  -- 节点表数组 + 每个 CONV 的 params 数据(拼成一个大 blob)

用法: python gen_unet_c.py [vectors目录] [输出src目录]
默认: vectors_small / E:/fpga/my_project/tcp_image_rx/src
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
VEC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "vectors_small")
SRC = sys.argv[2] if len(sys.argv) > 2 else r"E:/fpga/my_project/tcp_image_rx/src"

LANES = 8
FIELDS = ('name', 'kind', 'in0', 'in1', 'mode', 'ca', 'cb', 'h', 'w',
          'relu', 'shift', 'qmin', 'qmax', 'm0', 'm1')
KIND_ID = {'INPUT': 0, 'CONV': 1, 'ELT': 2}


def groups(c):
    return (c + LANES - 1) // LANES


def main():
    # plan.json 只在"张量全放片上 BRAM"那套（32x32 bring-up）里才有意义。
    # 全分辨率走条带调度，张量在 PS 内存里，不需要板上固定分配 —— 所以允许缺省。
    plan_path = os.path.join(VEC, "plan.json")
    if os.path.exists(plan_path):
        plan = json.load(open(plan_path))
        off_of = {p["name"]: p["off_words"] for p in plan["nodes"]}
        tensor_peak = plan["tensor_peak_words"]
        param_off = plan["param_off_words"]
        param_max = plan["max_param_bytes"]
        total_words = plan["total_words"]
        bram_words = plan.get("bram_words", 16384)
    else:
        plan = None
        off_of = {}
        tensor_peak = param_off = total_words = 0
        param_max = 0
        bram_words = 16384
        print("[gen] no plan.json -> strip-scheduled build (tensors live in PS memory)")

    nodes = []
    for line in open(os.path.join(VEC, "network.txt")):
        if not line.strip():
            continue
        f = line.split()
        n = dict(zip(FIELDS, f))
        for k in FIELDS[4:]:
            n[k] = int(n[k])
        oh, ow, oc = n["h"], n["w"], n["ca"]
        if n["kind"] == "CONV":
            oc = n["cb"]
            if n["mode"] == 2:
                oh, ow = 2 * oh, 2 * ow
        elif n["kind"] == "ELT":
            if n["mode"] == 1:
                oc = n["ca"] + n["cb"]
            elif n["mode"] == 2:
                oh, ow = oh // 2, ow // 2
        n.update(out_h=oh, out_w=ow, out_c=oc)
        nodes.append(n)

    idx = {n["name"]: i for i, n in enumerate(nodes)}

    # params 拼成一个大 blob, 记录每个 CONV 的偏移/长度
    blob = bytearray()
    par_off = [0] * len(nodes)
    par_len = [0] * len(nodes)
    for i, n in enumerate(nodes):
        if n["kind"] != "CONV":
            continue
        data = open(os.path.join(VEC, "params", n["name"] + ".bin"), "rb").read()
        assert len(data) % 8 == 0, n["name"]
        par_off[i] = len(blob)
        par_len[i] = len(data)
        blob += data

    inp = nodes[0]
    outp = nodes[-1]

    # ---------------- unet_net.h ----------------
    h = []
    h.append("/* AUTO-GENERATED by ai/net/gen_unet_c.py -- DO NOT EDIT.")
    h.append(" * Source vectors: %s" % os.path.basename(VEC))
    h.append(" * Network: %d nodes, %dx%d in, %d out channel(s)." %
             (len(nodes), inp["h"], inp["w"], outp["out_c"]))
    h.append(" */")
    h.append("#ifndef UNET_NET_H")
    h.append("#define UNET_NET_H")
    h.append("")
    h.append("#include <stdint.h>")
    h.append("")
    h.append("#define UNET_NODES_LEN        %du" % len(nodes))
    h.append("#define UNET_BRAM_BASE        0xB0000000u")
    h.append("#define UNET_BRAM_WORDS       %du        /* A1: 256 KB / 16 B (was 128 KB) */" % bram_words)
    h.append("#define UNET_TENSOR_PEAK_WORDS %du" % tensor_peak)
    h.append("#define UNET_PARAM_OFF_WORDS  %du" % param_off)
    h.append("#define UNET_PARAM_MAX_BYTES  %du" % param_max)
    h.append("#define UNET_TOTAL_WORDS      %du" % total_words)
    h.append("")
    h.append("#define UNET_IN_W             %du" % inp["w"])
    h.append("#define UNET_IN_H             %du" % inp["h"])
    h.append("#define UNET_IN_C             %du" % inp["ca"])
    h.append("#define UNET_OUT_W            %du" % outp["out_w"])
    h.append("#define UNET_OUT_H            %du" % outp["out_h"])
    h.append("#define UNET_OUT_C            %du" % outp["out_c"])
    h.append("")
    h.append("/* Vessel criterion: a pixel is vessel when logit >= UNET_THRESHOLD_DEFAULT. */")
    h.append("#define UNET_THRESHOLD_DEFAULT (-3)")
    h.append("")
    h.append("enum { UNET_KIND_INPUT = 0, UNET_KIND_CONV = 1, UNET_KIND_ELT = 2 };")
    h.append("")
    h.append("typedef struct {")
    h.append("    uint8_t  kind;        /* UNET_KIND_* */")
    h.append("    int8_t   in0, in1;    /* 上游节点下标, -1 = 无 */")
    h.append("    uint8_t  mode;        /* CONV: 0=3x3 1=1x1 2=2x2转置; ELT: 0=Add 1=Concat 2=MaxPool */")
    h.append("    uint8_t  ca, cb;      /* 输入/输出通道 */")
    h.append("    uint8_t  out_c;       /* 本节点输出通道数(CONV=cb, Concat=ca+cb, 其余=ca) */")
    h.append("    uint8_t  relu, shift;")
    h.append("    int16_t  qmin, qmax;")
    h.append("    int32_t  m0, m1;      /* ELT 两路乘数 */")
    h.append("    uint16_t in_h, in_w;  /* 喂给 kernel 的输入尺寸(512 基) */")
    h.append("    uint16_t out_h, out_w;/* 本节点输出尺寸(512 基) */")
    h.append("} unet_node_t;")
    h.append("")
    h.append("/* 条带调度用: 张量尺寸 = 表里的值按本次输入尺寸等比缩放(unet_set_shift / unet_set_size)。 */")
    h.append("")
    h.append("extern const unet_node_t unet_nodes[UNET_NODES_LEN];")
    h.append("extern const uint32_t     unet_param_off[UNET_NODES_LEN];  /* 相对 unet_params 的字节偏移 */")
    h.append("extern const uint32_t     unet_param_len[UNET_NODES_LEN];")
    h.append("extern const uint8_t      unet_params[];")
    h.append("extern const uint32_t     unet_params_bytes;")
    h.append("")
    h.append("#endif /* UNET_NET_H */")

    with open(os.path.join(SRC, "unet_net.h"), "w", encoding="utf-8") as f:
        f.write("\n".join(h) + "\n")

    # ---------------- unet_net_data.c ----------------
    c = []
    c.append("/* AUTO-GENERATED by ai/net/gen_unet_c.py -- DO NOT EDIT. */")
    c.append('#include "unet_net.h"')
    c.append("")
    c.append("const unet_node_t unet_nodes[UNET_NODES_LEN] = {")
    for n in nodes:
        c.append("    { %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d },"
                 % (KIND_ID[n["kind"]],
                    idx.get(n["in0"], -1) if n["in0"] != "-" else -1,
                    idx.get(n["in1"], -1) if n["in1"] != "-" else -1,
                    n["mode"], n["ca"], n["cb"], n["out_c"],
                    n["relu"], n["shift"], n["qmin"], n["qmax"],
                    n["m0"], n["m1"], n["h"], n["w"], n["out_h"], n["out_w"]))
    c.append("};")
    c.append("")
    c.append("const uint32_t unet_param_off[UNET_NODES_LEN] = {")
    c.append("    " + ", ".join(str(v) for v in par_off))
    c.append("};")
    c.append("")
    c.append("const uint32_t unet_param_len[UNET_NODES_LEN] = {")
    c.append("    " + ", ".join(str(v) for v in par_len)
             .replace(", ", ",").replace(" ", ""))
    c.append("};")
    c.append("")
    c.append("const uint32_t unet_params_bytes = %du;" % len(blob))
    c.append("")
    c.append("/* 16 字节对齐: 驱动会把它按 32bit 直接搬进 BRAM(Device 内存不允许非对齐访存) */")
    c.append("const uint8_t unet_params[%du] __attribute__((aligned(16))) = {" % max(len(blob), 1))
    for i in range(0, len(blob), 16):
        c.append("    " + " ".join("0x%02X," % b for b in blob[i:i + 16]))
    c.append("};")

    with open(os.path.join(SRC, "unet_net_data.c"), "w", encoding="utf-8") as f:
        f.write("\n".join(c) + "\n")

    # 给文档/PC 端用的元信息
    meta = dict(nodes=len(nodes), in_whc=[inp["h"], inp["w"], inp["ca"]],
                out_whc=[outp["out_h"], outp["out_w"], outp["out_c"]],
                tensor_peak_words=tensor_peak,
                param_off_words=param_off,
                param_bytes=len(blob), total_words=total_words,
                threshold=-3)
    json.dump(meta, open(os.path.join(VEC, "net_meta.json"), "w"), indent=1)

    print("[gen] unet_net.h + unet_net_data.c -> %s" % SRC)
    print("      nodes=%d  in=%dx%dx%d  out=%dx%dx%d  params=%d B"
          % (len(nodes), inp["h"], inp["w"], inp["ca"],
             outp["out_h"], outp["out_w"], outp["out_c"], len(blob)))
    if plan is not None:
        print("      (on-chip plan: peak=%d param_off=%d total=%d/%d words)"
              % (tensor_peak, param_off, total_words, bram_words))


if __name__ == "__main__":
    main()
